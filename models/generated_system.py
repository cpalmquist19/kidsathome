"""
Generated system model for Kids at Home application.
Stores data from the space system generator.
"""

from flask_sqlalchemy import SQLAlchemy
from datetime import datetime
from . import db


class GeneratedSystem(db.Model):
    """
    Generated system model for storing space system generation data.
    
    Attributes:
        id (int): Primary key
        user_id (int): Foreign key to users table (optional)
        system_data (dict): JSON data of the generated system
        created_at (datetime): Generation timestamp
        ip_address (str): IP address of the user who generated it
    """
    
    __tablename__ = 'generated_systems'
    
    # Primary fields
    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=True, index=True)
    system_data = db.Column(db.JSON, nullable=True)
    ip_address = db.Column(db.String(45), nullable=True)
    
    # Timestamps
    created_at = db.Column(db.DateTime, default=datetime.utcnow, nullable=False, index=True)
    
    def __repr__(self):
        return f'<GeneratedSystem {self.id}>'
    
    def get_system_name(self):
        """
        Extract system name from system data.
        
        Returns:
            str: System name or 'Unknown System'
        """
        if self.system_data and isinstance(self.system_data, dict):
            return self.system_data.get('name', 'Unknown System')
        return 'Unknown System'
    
    def get_star_type(self):
        """
        Extract star type from system data.
        
        Returns:
            str: Star type or 'Unknown'
        """
        if self.system_data and isinstance(self.system_data, dict):
            star = self.system_data.get('star', {})
            if isinstance(star, dict):
                return star.get('type', 'Unknown')
        return 'Unknown'
    
    def get_planet_count(self):
        """
        Get number of planets in the system.
        
        Returns:
            int: Number of planets
        """
        if self.system_data and isinstance(self.system_data, dict):
            planets = self.system_data.get('planets', [])
            if isinstance(planets, list):
                return len(planets)
        return 0
    
    def is_habitable(self):
        """
        Check if the system contains habitable planets.
        
        Returns:
            bool: True if system has habitable planets
        """
        if self.system_data and isinstance(self.system_data, dict):
            planets = self.system_data.get('planets', [])
            if isinstance(planets, list):
                for planet in planets:
                    if isinstance(planet, dict) and planet.get('habitable', False):
                        return True
        return False
    
    @classmethod
    def create_system(cls, system_data, user_id=None, ip_address=None):
        """
        Create a new generated system record.
        
        Args:
            system_data (dict): System generation data
            user_id (int, optional): ID of user who generated it
            ip_address (str, optional): IP address of user
            
        Returns:
            GeneratedSystem: New system instance
        """
        return cls(
            user_id=user_id,
            system_data=system_data,
            ip_address=ip_address
        )
    
    @classmethod
    def get_user_systems(cls, user_id, limit=50):
        """
        Get systems generated by a specific user.
        
        Args:
            user_id (int): User ID
            limit (int): Maximum number of systems to return
            
        Returns:
            list: List of GeneratedSystem objects
        """
        return cls.query.filter_by(user_id=user_id)\
                       .order_by(cls.created_at.desc())\
                       .limit(limit).all()
    
    @classmethod
    def get_recent_systems(cls, limit=20):
        """
        Get recently generated systems.
        
        Args:
            limit (int): Maximum number of systems to return
            
        Returns:
            list: List of GeneratedSystem objects
        """
        return cls.query.order_by(cls.created_at.desc()).limit(limit).all()
    
    @classmethod
    def get_system_stats(cls):
        """
        Get statistics about generated systems.
        
        Returns:
            dict: Statistics about systems
        """
        total_systems = cls.query.count()
        user_systems = cls.query.filter(cls.user_id.isnot(None)).count()
        anonymous_systems = total_systems - user_systems
        
        # Get systems from last 24 hours
        yesterday = datetime.utcnow() - timedelta(days=1)
        recent_systems = cls.query.filter(cls.created_at >= yesterday).count()
        
        return {
            'total_systems': total_systems,
            'user_systems': user_systems,
            'anonymous_systems': anonymous_systems,
            'recent_systems_24h': recent_systems
        }
    
    def to_dict(self):
        """
        Convert system object to dictionary.
        
        Returns:
            dict: System data
        """
        return {
            'id': self.id,
            'user_id': self.user_id,
            'system_data': self.system_data,
            'ip_address': self.ip_address,
            'created_at': self.created_at.isoformat() if self.created_at else None,
            'system_name': self.get_system_name(),
            'star_type': self.get_star_type(),
            'planet_count': self.get_planet_count(),
            'is_habitable': self.is_habitable()
        }
