#!/usr/bin/env python3
"""
Build static/data/bismuth_objects.js (Gravity Lab catalog entries) from the
Bismuth{n}.jpg images in static/images/Bismuth (n >= 4; Bismuth1-3 and every
other file in that folder are skipped).

- the output is renumbered from 1 in source order (Bismuth4 -> 1, Bismuth5 -> 2, ...),
  so the displayed name is "Eanorgath <The Magnatar Moon> {i}"
- every image becomes its own object with Eanorgath <The Magnatar Moon>'s stats
  (0.2 Earth masses, 0.4 Earth radii); the name uses &lt; &gt; because
  names are rendered as HTML and a literal <...> would vanish as a tag
- images are shrunk to --max-size px and written as .webp into
  static/images/eanorgath/ (the source folder is left untouched)

Usage:
    python scripts/build_bismuth_objects.py
    python scripts/build_bismuth_objects.py --max-size 800 --quality 80
"""
import argparse
import json
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "static", "images", "Bismuth")
IMG_DIR = os.path.join(ROOT, "static", "images", "eanorgath")
IMG_URL_BASE = "/static/images/eanorgath"
OUT_JS = os.path.join(ROOT, "static", "data", "bismuth_objects.js")

MIN_N = 4
EARTH_MASS = 5.97237e24
EARTH_RADIUS = 6.371e6
TYPE = "eanorgath"
FILTER_LABEL = "Eanorgath"
DESCRIPTION = (
    "Eanorgath &lt;The Magnatar Moon&gt;<br>"
    "Mass: 0.2 Earths.<br>Radius: 0.4 Earths.<br>"
    "Gravitational Trap: if you were on it, it would act like it had INFINITE mass, "
    "but not in space."
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-size", type=int, default=640)
    ap.add_argument("--quality", type=int, default=80)
    args = ap.parse_args()

    found = []
    for fn in os.listdir(SRC_DIR):
        m = re.fullmatch(r"Bismuth(\d+)\.jpe?g", fn, re.IGNORECASE)
        if m and int(m.group(1)) >= MIN_N:
            found.append((int(m.group(1)), fn))
    found.sort()

    os.makedirs(IMG_DIR, exist_ok=True)
    for old in os.listdir(IMG_DIR):  # stale numbering from earlier runs
        if re.fullmatch(r"bismuth\d+\.webp", old):
            os.remove(os.path.join(IMG_DIR, old))
    entries = []
    for i, (_, fn) in enumerate(found, start=1):
        dest = os.path.join(IMG_DIR, f"bismuth{i}.webp")
        with Image.open(os.path.join(SRC_DIR, fn)) as im:
            im = im.convert("RGB")
            im.thumbnail((args.max_size, args.max_size), Image.LANCZOS)
            im.save(dest, "WEBP", quality=args.quality, method=6)
        entries.append(
            f"    'eanorgath_bismuth{i}': {{\n"
            f"        name: {json.dumps(f'Eanorgath &lt;The Magnatar Moon&gt; {i}', ensure_ascii=False)},\n"
            f"        mass: 0.2 * {EARTH_MASS:.5e},\n"
            f"        radius: 0.4 * {EARTH_RADIUS:.4e},\n"
            f"        icon: '🌙',\n"
            f"        type: '{TYPE}',\n"
            f"        image: '{IMG_URL_BASE}/bismuth{i}.webp',\n"
            f"        description: {json.dumps(DESCRIPTION, ensure_ascii=False)}\n"
            "    },"
        )

    out = (
        "// Generated by scripts/build_bismuth_objects.py - do not edit by hand.\n"
        "window.BISMUTH_DATA = {\n" + "\n".join(entries) + "\n};\n\n"
        f"window.BISMUTH_FILTERS = [\n    ['{TYPE}', '{FILTER_LABEL}']\n];\n"
    )
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with open(OUT_JS, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"wrote {len(entries)} entries -> {OUT_JS} (Bismuth{found[0][0]}..Bismuth{found[-1][0]})")


if __name__ == "__main__":
    main()
